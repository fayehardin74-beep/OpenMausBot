// mausbridge: build a dsh --patch overlay that gives `dsh --profile acp` the desktop's agent presets.
// Desktop sessions record the preset they run (usually `ptc`, whose only model-facing tool is
// run_code). The acp profile has no preset registry, so a resumed desktop session gets the base
// toolset, dsh defers every tool it did not start with, and DeepSeek rejects the request.
// This copies the agent-plane rows and preset declarations from the installed dsh-web-app bundle,
// so a DeepSeek update is picked up by re-running this script, not by editing YAML by hand.
//
// Run with DeepSeek's own runtime (it can read app.asar):
//   ELECTRON_RUN_AS_NODE=1 "<DeepSeek Harness.app>/Contents/MacOS/DeepSeek Harness" make-dsh-presets-patch.cjs <app> <out.yml>
const fs = require("node:fs");
const path = require("node:path");

const [app, out] = process.argv.slice(2);
if (!app || !out) {
  console.error("usage: make-dsh-presets-patch.cjs <DeepSeek Harness.app> <out.yml>");
  process.exit(64);
}
const webApp = path.join(app, "Contents/Resources/app.asar/dsh/node_modules/@deepseek-ai/dsh-web-app");
const manifest = JSON.parse(fs.readFileSync(path.join(webApp, "package.json"), "utf8"));
const bundle = fs.readFileSync(path.join(webApp, "cordis.patch.yml"), "utf8");

// The web patch's tail, from this marker on, is the agent plane: base tool rows disabled and the
// preset registry inserted. Everything above it is browser/host surface the acp profile must not mount.
const marker = "# ── the agent plane moves behind agent presets";
const at = bundle.indexOf(marker);
if (at < 0) throw new Error(`dsh-web-app ${manifest.version}: agent-plane marker not found; the layout changed`);

// Presets that need host services the acp process does not run (the cordis preset wants the
// cordis host runner) are left out; a session recorded on one of them fails loudly instead.
const presets = ["standard", "ptc", "minimal"];
const parts = [
  `# Generated by scripts/mausbridge/make-dsh-presets-patch.cjs from @deepseek-ai/dsh-web-app ${manifest.version}.`,
  "# Do not edit; re-run the script after a DeepSeek Harness update.",
  bundle.slice(at),
  ...presets.map((id) => fs.readFileSync(path.join(webApp, "presets", `${id}.patch.yml`), "utf8")),
];
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, parts.join("\n"));
console.log(`wrote ${out} (dsh-web-app ${manifest.version}, presets: ${presets.join(", ")})`);
